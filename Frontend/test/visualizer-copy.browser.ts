import assert from 'node:assert/strict'
import { expect, type Page } from '@playwright/test'

export async function verifyVisualizerCopy(page: Page, url: string, database: string) {
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto(`${url}/visualizer`)
  const visualizer = page.getByRole('region', { name: 'Schema visualizer', exact: true })
  await expect(visualizer).toBeVisible()
  await expect(visualizer.getByText('items', { exact: true })).toBeVisible()
  await expect(visualizer.locator('svg.lucide-ellipsis-vertical, svg.lucide-more-vertical')).toHaveCount(0)
  await expect(visualizer.getByRole('button', { name: /schema.*public/i })).toHaveCount(0)
  await expect(visualizer.getByRole('combobox')).toHaveCount(0)
  const button = page.getByRole('button', { name: 'Copy as SQL', exact: true })
  await expect(button).toBeEnabled()
  const endpoint = `${url}/api/studio/databases/${database}/schema/sql`
  const response = await page.request.get(endpoint)
  assert.equal(response.status(), 200)
  const exported = await response.json()
  assert.equal(exported.database, database)
  assert.match(exported.sql, /CREATE TABLE public\.items/)
  assert.match(exported.sql, /CREATE TABLE public\.comments/)
  assert.match(exported.sql, /GENERATED BY DEFAULT AS IDENTITY/)
  assert.match(exported.sql, /FOREIGN KEY/)
  assert.doesNotMatch(exported.sql, /seed record|^COPY |^INSERT INTO /m)
  assert.equal((await fetch(endpoint)).status, 401)

  // Reproduce an HTTP VPS with no navigator.clipboard.
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined }))
  await button.click()
  await expect(page.locator('[data-studio-toast]').filter({ hasText: 'Copied SQL schema for all tables!' })).toBeVisible()
  await page.evaluate(() => Reflect.deleteProperty(navigator, 'clipboard'))
  const fallbackCopy = await page.evaluate(() => navigator.clipboard.readText())
  assert.match(fallbackCopy, /CREATE TABLE public\.items/)
  assert.match(fallbackCopy, /CREATE TABLE public\.comments/)

  // Failure reports an error, leaves the previous clipboard intact and allows retry.
  await page.route('**/schema/sql', route => route.fulfill({
    status: 503, contentType: 'application/json', body: '{"error":"Schema export unavailable"}',
  }))
  await button.click()
  await expect(page.locator('[data-studio-toast][role="alert"]').filter({ hasText: 'Schema export unavailable' })).toBeVisible()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), fallbackCopy)
  await expect(button).toBeEnabled()
  await page.unroute('**/schema/sql')
  const retry = page.waitForResponse(response => response.url() === endpoint && response.ok())
  await button.click()
  await retry
  await expect(button).toBeEnabled()
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /CREATE TABLE public\.comments/)

  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: undefined }))
  await page.getByRole('button', { name: 'More export options', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Copy as Markdown', exact: true }).click()
  await expect(page.locator('[data-studio-toast]').filter({ hasText: 'Copied Markdown schema to clipboard!' })).toBeVisible()
  await page.evaluate(() => Reflect.deleteProperty(navigator, 'clipboard'))
  assert.match(await page.evaluate(() => navigator.clipboard.readText()), /Table: `items`/)
  console.log('PASS: Visualizer copies all real table DDL without row data, HTTP clipboard fallback, Markdown copy and export failure/retry')
}
